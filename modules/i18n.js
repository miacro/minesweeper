function format(message, values) {
  return message.replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? ''));
}

export function createI18n(initialLanguage = 'en') {
  let language = MESSAGES[initialLanguage] ? initialLanguage : 'en';

  return {
    get languages() {
      return Object.entries(MESSAGES).map(([code, messages]) => ({
        code,
        name: messages.name,
      }));
    },
    get language() {
      return language;
    },
    setLanguage(nextLanguage) {
      language = MESSAGES[nextLanguage] ? nextLanguage : 'en';
    },
    t(key, values = {}) {
      return format(MESSAGES[language][key] || MESSAGES.en[key] || key, values);
    },
    translateError(message) {
      return language === 'zh-CN' ? ERROR_TRANSLATIONS[message] || message : message;
    },
  };
}
